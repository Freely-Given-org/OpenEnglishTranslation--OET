"""
Write a Markdown table of each OET-RV book's \\mt title lines,
    \\h, \\toc1, \\toc2 and \\toc3 headers, and \\id version number.

The output is only rewritten when its contents change,
    so make sees an unchanged timestamp otherwise.

CHANGELOG:
    2026-11-20 First version
"""
from pathlib import Path
import re


LAST_MODIFIED_DATE = '2026-11-20'
SHORT_PROGRAM_NAME = "create_OET-RV_book_titles_table"
PROGRAM_NAME = "Make OET-RV book titles table"
PROGRAM_VERSION = '0.01'
PROGRAM_NAME_VERSION = f'{SHORT_PROGRAM_NAME} v{PROGRAM_VERSION}'


project_folderpath = Path(__file__).parent.parent # Find folders relative to this module
RV_folderpath = project_folderpath / 'translatedTexts/ReadersVersion'
output_filepath = RV_folderpath / 'OET-RV_book_titles.md'

BOOK_ORDER = '''FRT INT
GEN EXO LEV NUM DEU JOS JDG RUT SA1 SA2 KI1 KI2 CH1 CH2 EZR NEH EST JOB PSA PRO ECC SNG
ISA JER LAM EZE DAN HOS JOL AMO OBA JNA MIC NAH HAB ZEP HAG ZEC MAL
MAT MRK LUK JHN ACT ROM CO1 CO2 GAL EPH PHP COL TH1 TH2 TI1 TI2 TIT PHM HEB JAM PE1 PE2 JN1 JN2 JN3 JDE REV
TOB JDT ESG WIS SIR BAR MA1 MA2 ES1 ES2 MAN PS2 MA3 MA4 DAG LAO'''.split()

HEADER_MARKERS = ('h', 'toc1', 'toc2', 'toc3')
# Once a title has started, any of these marks the end of the title block
TITLE_END_MARKERS = ('c', 'is1', 'is2', 'ip', 'p', 's1')


def escape( text:str ) -> str:
    """ Stop text from breaking the Markdown table. """
    return text.replace( '|', '\\|' )


def extract_book_info( filepath:Path ) -> dict:
    """ Return the title, header and version fields of one ESFM book. """
    info = { 'mt':[], 'version':'' }
    for marker in HEADER_MARKERS: info[marker] = []
    with open( filepath, 'rt', encoding='utf-8' ) as esfm_file:
        for line in esfm_file:
            match = re.match( r'\\(\w+)\s?(.*)', line.rstrip( '\n' ) )
            if not match: continue
            marker, text = match.groups()
            if marker == 'id':
                version_match = re.search( r'[vV]\d+\.\d+\.\d+', text )
                if version_match: info['version'] = version_match.group(0)
            elif marker in HEADER_MARKERS:
                info[marker].append( escape(text) )
            elif re.fullmatch( r'mt\d?', marker ):
                info['mt'].append( f'`{marker}` {escape(text)}' )
            elif marker in TITLE_END_MARKERS and info['mt']:
                break
    return info


def make_table() -> str:
    """ Return the complete Markdown document. """
    available = { path.stem[7:]: path for path in RV_folderpath.glob( 'OET-RV_???.ESFM' ) }
    book_codes = [code for code in BOOK_ORDER if code in available] \
                    + sorted( set(available) - set(BOOK_ORDER) )
    lines = [ '# OET-RV book titles and headers', '',
              f'Generated by `scripts/{SHORT_PROGRAM_NAME}.py` from the `OET-RV_*.ESFM` files. Don’t edit this file by hand.', '',
              '`\\mt` lines are listed in file order.', '',
              '| Book | Title lines (`\\mt`) | `\\h` | `\\toc1` | `\\toc2` | `\\toc3` | Version |',
              '|---|---|---|---|---|---|---|' ]
    for code in book_codes:
        info = extract_book_info( available[code] )
        cells = [ code, '<br>'.join(info['mt']) ] \
                + [ '<br>'.join(info[marker]) for marker in HEADER_MARKERS ] \
                + [ info['version'] ]
        lines.append( f"| {' | '.join(cells)} |" )
    return '\n'.join( lines ) + '\n'


def main() -> None:
    new_text = make_table()
    old_text = output_filepath.read_text( encoding='utf-8' ) if output_filepath.is_file() else None
    if new_text == old_text:
        print( f"{PROGRAM_NAME_VERSION}: {output_filepath.name} is unchanged." )
    else:
        output_filepath.write_text( new_text, encoding='utf-8' )
        print( f"{PROGRAM_NAME_VERSION}: wrote {output_filepath.name}." )


if __name__ == '__main__':
    main()
